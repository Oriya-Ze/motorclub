export const LANGUAGE_STORAGE_KEY = "motorclub_language";

export type AppLanguage = "he" | "en";

function readStoredLanguage(): AppLanguage | null {
  try {
    const stored = localStorage.getItem(LANGUAGE_STORAGE_KEY);
    return stored === "en" || stored === "he" ? stored : null;
  } catch {
    return null;
  }
}

function readDocumentLanguage(): AppLanguage {
  const docLang = document.documentElement.lang;
  return docLang === "en" ? "en" : "he";
}

export function resolveAppLanguage(): AppLanguage {
  const active = i18n.language || i18n.resolvedLanguage;
  if (active?.startsWith("en")) return "en";
  if (active?.startsWith("he")) return "he";
  return readStoredLanguage() ?? readDocumentLanguage();
}

export function applyAppLanguage(language: AppLanguage) {
  try {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
  } catch {
    // ignore storage failures (private mode, etc.)
  }
  document.documentElement.lang = language;
  document.documentElement.dir = language === "he" ? "rtl" : "ltr";
}

const initialLanguage = readStoredLanguage() ?? readDocumentLanguage();
applyAppLanguage(initialLanguage);

i18n.use(initReactI18next).init({
  resources,
  lng: initialLanguage,
  fallbackLng: "he",
  supportedLngs: ["he", "en"],
  nonExplicitSupportedLngs: true,
  interpolation: { escapeValue: false },
});

export default i18n;
